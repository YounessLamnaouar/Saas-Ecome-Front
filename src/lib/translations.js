export function translate(text, language = localStorage.getItem('language') || 'en') {
  if (typeof text !== 'string') return text;
  const locale = language.split('-')[0];
  const dictionary = locale === 'ar' ? arabicPhrases : locale === 'fr' ? translations : {};
  if (dictionary[text]) return dictionary[text];
  for (const [source, target] of Object.entries(dictionary)) {
    if (!source.includes('{0}')) continue;
    const parts = source.split(/\{\d+\}/).map(s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'));
    const match = text.match(new RegExp('^' + parts.join('(.*?)') + '$'));
    if (match) return target.replace(/\{(\d+)\}/g, (_, index) => match[Number(index) + 1]);
  }
  return text;
}
